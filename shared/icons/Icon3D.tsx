export function Icon3D({ name, size = 20, color, animated = false, className, style }: Props) {
  const isAnimated = animated || ANIMATED_DEFAULT.has(name);
  const stroke = color ?? "currentColor";
  const filled = name === "dot";

  return (
    <span
      className={[
        "icon-3d",
        `icon-3d--${name}`,
        isAnimated ? "is-animated" : "",
        className,
      ]
        .filter(Boolean)
        .join(" ")}
      style={{
        display: "inline-flex",
        alignItems: "center",
        justifyContent: "center",
        width: size,
        height: size,
        verticalAlign: "middle",
        flexShrink: 0,
        color: stroke,
        ...style,
      }}
      aria-hidden
    >
      <svg
        viewBox="0 0 24 24"
        width={size}
        height={size}
        fill={filled ? "currentColor" : "none"}
        stroke={filled ? "none" : "currentColor"}
        strokeWidth={filled ? 0 : 2}
        strokeLinecap="round"
        strokeLinejoin="round"
      >
        {ICON_PATHS[name]}
      </svg>
    </span>
  );
}
