export const catalogs: Record<Locale, Messages> = { en, fa, ar, es, fr };

export function isRtl(locale: Locale): boolean {
  return locale === "fa" || locale === "ar";
}

export function translate(locale: Locale, key: string): string {
  return catalogs[locale]?.[key] ?? catalogs.en[key] ?? key;
}

/** Map backend agent name to i18n key */
const AGENT_KEYS: Record<string, string> = {
  "Commander AI": "agent_commander",
  "Emergency AI": "agent_emergency",
  "Medical AI": "agent_medical",
  "Transportation AI": "agent_transportation",
  "Power AI": "agent_power",
  "Water AI": "agent_water",
  "Fire AI": "agent_fire",
  "Police AI": "agent_police",
  "Food AI": "agent_food",
  "Construction AI": "agent_construction",
  "Economic AI": "agent_economic",
  "Communication AI": "agent_communication",
};

export function translateAgent(locale: Locale, name: string): string {
  const key = AGENT_KEYS[name];
  return key ? translate(locale, key) : name;
}

export function translateDisaster(locale: Locale, id: string): string {
  return translate(locale, `disaster_${id}`);
}

export function translateDna(locale: Locale, key: string): string {
  return translate(locale, `dna_${key}`);
}

export function translateStrategy(locale: Locale, strategyId: string): string {
  return translate(locale, `strategy_${strategyId}`);
}

export function translateScenario(locale: Locale, scenarioId: string): string {
  return translate(locale, `scenario_${scenarioId}`);
}

